def f(x): return ("%.4f"%x).rstrip('0').rstrip('.')+"f" if abs(x)>1e-9 else "0f"
def v3(a): return "new Vector3(%s, %s, %s)"%(f(a[0]),f(a[1]),f(a[2]))
def col(c,fur): return "new Color(%s, %s, %s, %s)"%(f(c[0]),f(c[1]),f(c[2]),f(fur))

def emit_shape(q):
    if q.t=='E':
        Rt=q.kw['R'].T
        return "SdfShape.Ellipsoid(%s, %s, %s, %s, %s, %s, %s)"%(v3(q.kw['c']),v3(q.kw['r']),v3(Rt[0]),v3(Rt[1]),v3(Rt[2]),f(q.k),col(q.col,q.fur))
    if q.t=='C':
        return "SdfShape.Capsule(%s, %s, %s, %s, %s, %s)"%(v3(q.kw['a']),v3(q.kw['b']),f(q.kw['ra']),f(q.kw['rb']),f(q.k),col(q.col,q.fur))
    if q.t=='T':
        Rt=q.kw['R'].T
        return "SdfShape.Torus(%s, %s, %s, %s, %s, %s, %s, %s)"%(v3(q.kw['c']),v3(Rt[0]),v3(Rt[1]),v3(Rt[2]),f(q.kw['Rm']),f(q.kw['rm']),f(q.k),col(q.col,q.fur))

def method(name,parts,paints):
    s="    public static SdfShape[] %sShapes()\n    {\n        return new SdfShape[]\n        {\n"%name
    s+=",\n".join("            "+emit_shape(q) for q in parts)+"\n        };\n    }\n\n"
    s+="    public static SdfPaint[] %sPaints()\n    {\n        return new SdfPaint[]\n        {\n"%name
    if paints:
        s+=",\n".join("            new SdfPaint(%s, %s, %s, %s)"%(v3(p[0]),f(p[1]),f(p[2]),col(p[3],p[4])) for p in paints)+"\n"
    s+="        };\n    }\n\n"
    return s

